    };

    /// <summary>Генерирует описание планеты.</summary>
    public static string DescribePlanet(DeterministicRandom random, PlanetData planet)
    {
        var parts = new List<string>
        {
            $"Планета {planet.Name}. {PlanetTypeDescription(planet.Type)}, " +
            $"гравитация {planet.Gravity:0.0}g, атмосфера из {planet.Atmosphere}.",
        };

        parts.Add(planet.HasLife
            ? planet.HasAggressiveFauna
                ? "Жизнь имеется. Фауна агрессивна и, судя по всему, голодна."
                : "Жизнь имеется, но ведёт себя прилично."
            : "Флора и фауна отсутствуют.");

        parts.Add(random.Pick(PlanetFlavor));
        return string.Join(' ', parts);
    }

    /// <summary>Генерирует описание корабля.</summary>
    public static string DescribeShip(DeterministicRandom random, ShipData ship)
    {
        return $"Корабль {ship.Name}, класс «{ship.Type}». {random.Pick(ShipFlavor)}";
    }

    /// <summary>Генерирует описание космической станции.</summary>
    public static string DescribeStation(DeterministicRandom random)
        => random.Pick(StationFlavor);

    private static string PlanetTypeDescription(PlanetType type) => type switch
    {
        PlanetType.Rocky => "Каменистая",
        PlanetType.GasGiant => "Газовый гигант",
        PlanetType.Ice => "Ледяная",
        PlanetType.Oceanic => "Океаническая",
        PlanetType.Volcanic => "Вулканическая",
        PlanetType.Toxic => "Токсичная",
        PlanetType.Radioactive => "Радиоактивная",
        PlanetType.Desert => "Пустынная",
        PlanetType.Jungle => "Джунглевая",
        PlanetType.Exotic => "Экзотическая",
        _ => "Неизвестная",
    };
}
