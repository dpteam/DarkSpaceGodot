    /// <summary>Возвращает элемент по идентификатору.</summary>
    /// <exception cref="ArgumentOutOfRangeException">Если идентификатор вне диапазона.</exception>
    public static Element GetById(int id)
    {
        if (id < 0 || id >= Elements.Length)
        {
            throw new ArgumentOutOfRangeException(nameof(id), id, $"Нет элемента с id={id}.");
        }

        return Elements[id];
    }

    /// <summary>Возвращает полный список элементов (только для чтения).</summary>
    public static IReadOnlyList<Element> All => Elements;

    /// <summary>Возвращает элемент по корню имени (например, «Гидро»).</summary>
    /// <returns>Элемент или <see langword="null"/>, если корень не найден.</returns>
