    /// <summary>Количество базовых предметов в каталоге.</summary>
    public static int Count => Entries.Length;

    /// <summary>Возвращает базовый предмет по идентификатору.</summary>
    /// <exception cref="ArgumentOutOfRangeException">Если идентификатор вне диапазона.</exception>
    public static Item GetById(int id)
    {
        if (id < 0 || id >= Entries.Length)
        {
            throw new ArgumentOutOfRangeException(nameof(id), id, $"Нет предмета с id={id}.");
        }

        return Entries[id];
    }

    /// <summary>Возвращает полный список базовых предметов (только для чтения).</summary>
    public static IReadOnlyList<Item> All => Entries;

    /// <summary>Возвращает все предметы указанной категории.</summary>
    public static IReadOnlyList<Item> ByCategory(ItemCategory category)
        => Entries.Where(e => e.Category == category).ToList();
