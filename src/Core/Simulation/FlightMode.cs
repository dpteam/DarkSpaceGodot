namespace DarkSpace.Core.Simulation;

/// <summary>
/// Модель полёта корабля.
/// </summary>
public enum FlightMode
{
    /// <summary>
    /// Элитовская (arcade-space) модель: скорость всегда направлена вдоль носа корабля,
    /// скалярная скорость с максимумом, тангаж/крен для разворота. Ощущается как в Elite —
    /// «крен + ручка на себя». Гравитация на корабль не действует.
    /// </summary>
    EliteAligned,

    /// <summary>
    /// Ньютоновская модель: скорость интегрируется независимо от ориентации, действует
    /// гравитация звезды. Даёт настоящую инерцию/дрейф (для «физических» режимов и тестов законов).
    /// </summary>
    Newtonian,
}
