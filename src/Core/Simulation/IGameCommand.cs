namespace DarkSpace.Core.Simulation;

/// <summary>
/// Игровая команда (интент) — атомарное действие, отправляемое клиентом.
/// </summary>
/// <remarks>
/// Архитектурный принцип проекта: UI и клиент <b>не мутируют</b> состояние мира напрямую,
/// а лишь отправляют команды. Мир применяет их детерминированно (см. <see cref="WorldSimulation"/>).
/// Это одинаково работает и в одиночной игре, и в авторитарном мультиплеере, где команды
/// проверяет сервер.
/// </remarks>
public interface IGameCommand
{
    /// <summary>Тип команды.</summary>
    CommandType Type { get; }

    /// <summary>Идентификатор игрока-отправителя.</summary>
    int PlayerId { get; }

    /// <summary>Порядковый номер команды от данного игрока (для упорядочивания и отсечения дублей).</summary>
    long Sequence { get; }
}
